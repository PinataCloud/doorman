/**
 * Gemini CLI host adapter for the PreToolUse guard.
 *
 * PURE, like every descriptor here: document text in / document text out,
 * stdin JSON → GuardHookInput, decision → stdout + exit code. No fs, no
 * process, no imports outside main/guard/ (the whole directory is copied into
 * userData and run with plain `node`).
 *
 * ── The host, as documented ────────────────────────────────────────────────
 * Sources, all fetched 2026-09-05:
 *   [1] https://geminicli.com/docs/hooks/
 *   [2] https://geminicli.com/docs/hooks/reference/
 *   [3] https://geminicli.com/docs/hooks/writing-hooks/
 *   [4] https://geminicli.com/docs/reference/configuration/
 *   [5] https://geminicli.com/docs/tools/{shell,file-system,web-fetch}/
 *   [6] https://github.com/google-gemini/gemini-cli/blob/main/docs/hooks/reference.md
 *
 * DOCUMENTS [1][4]. Hooks live in `settings.json` under a top-level `hooks`
 * object. Gemini CLI merges the layers "in the following order of precedence
 * (highest to lowest): 1. Project settings `.gemini/settings.json` in the
 * current directory. 2. User settings `~/.gemini/settings.json`. 3. System
 * settings. 4. Extensions." [1]. **Consequence for us:** we install at the
 * USER level, and a project that ships its own `.gemini/settings.json` sits
 * ABOVE it. The docs say "merges" but never say whether a project
 * `hooks.BeforeTool` array concatenates with the user one or replaces it —
 * that is genuinely undocumented, so the honest posture is: install user,
 * DOCTOR both (documents() returns both), and treat a project document that
 * carries its own `BeforeTool` as "this project may not be guarded" rather
 * than assuming either behaviour. The system document is returned too, for
 * the doctor only — on macOS it is
 * `/Library/Application Support/GeminiCli/settings.json`, overridable by
 * `GEMINI_CLI_SYSTEM_SETTINGS_PATH` [4], and in the general settings
 * precedence it outranks even the project file. There is no documented env
 * var that moves the USER directory off `~/.gemini` (no `GEMINI_HOME`,
 * no `GEMINI_CONFIG_DIR`, no XDG support) [4].
 *
 * SCHEMA [1][2]. One `hooks.BeforeTool` array of groups:
 *   { "matcher": "<regex>", "sequential": <bool>,
 *     "hooks": [ { "name": <string>, "type": "command",
 *                  "command": <string>, "timeout": <ms>,
 *                  "description": <string> } ] }
 * `matcher` is "compared against the name of the tool being executed" and
 * "supports regular expressions (for example, `read_.*`)" [6]; to match all
 * tools the docs give `"*"` or `""` [1] — we write `"*"`.
 * `timeout` is "Execution timeout in milliseconds (default: 60000)" [2][6] —
 * MILLISECONDS, not seconds, which is why merge() multiplies. We write it
 * ourselves, so `fixedTimeoutSeconds` is deliberately absent.
 *
 * COMMENTS. Gemini CLI reads settings.json through strip-json-comments and
 * then `JSON.parse` (verified 2026-10-19): `//` and `/* *\/` comments are legal,
 * a trailing comma is fatal. So the document is `jsonc`, read in that dialect
 * and edited in place (guard/jsonc.ts) so a person's comments survive.
 *
 * STDIN [2][6]. Common fields: `session_id`, `transcript_path`, `cwd`,
 * `hook_event_name`, `timestamp`. BeforeTool adds `tool_name` (string),
 * `tool_input` (object — "the raw arguments generated by the model"),
 * `mcp_context` (object, optional — "metadata for MCP-based tools") and
 * `original_request_name`.
 *
 * STDOUT [2][3][6]. Documented keys: `decision` ("allow" or "deny", alias
 * "block"), `reason` ("the feedback/error message provided when a decision is
 * deny"), `systemMessage` ("displayed immediately to the user in the
 * terminal"), `continue`, `stopReason`, `suppressOutput`,
 * `hookSpecificOutput`. `decision` is NOT required — `{}` is documented as
 * "do nothing" [3] — so our warn body carries `systemMessage` alone.
 * "Your script **must not** print any plain text to `stdout` other than the
 * final JSON" [2]: stdout here is pure `JSON.stringify` or nothing at all.
 *
 * EXIT CODES [2][6]. 0 = "Success. stdout is parsed as JSON. **Preferred for
 * all logic.**"; 2 = "System Block. The action is blocked; stderr is used as
 * the rejection reason."; any other non-zero = "Warning. A non-fatal failure
 * occurred; the CLI continues with a warning." So a deny goes out as exit 0
 * plus `{"decision":"deny"}` — exit 2 would put our reason on stderr instead
 * of in the documented field — and `exitSemantics` is "fail-open".
 *
 * NO NATIVE ASK [1][3]. Nothing in the hook contract prompts the human; the
 * only verdicts are allow and deny. Gemini therefore takes the Codex path
 * (hold.ts `hookOutputForHost`): the app mediates the question, and when it
 * cannot, we warn visibly and let the call continue.
 */

import type { GuardHookInput } from "../decision.js";
import { HOOK_TIMEOUT_SLACK_SECONDS, isGuardCommand } from "../policy.js";
import type { GuardHostDescriptor, HostDocument, HostEmit } from "./types.js";
import { readHostJson, writeHostJson, type JsoncDialect } from "../jsonc.js";

/** The one event we evaluate. */
const EVENT = "BeforeTool";

/** Match every tool: the docs give `"*"` or `""` for "all tools" [1]. */
const MATCH_ALL = "*";

/** macOS system settings file [4]; read for the doctor, never written. */
const MAC_SYSTEM_SETTINGS = "/Library/Application Support/GeminiCli/settings.json";

const INVALID_DOCUMENT = "~/.gemini/settings.json";

/** strip-json-comments, then JSON.parse: comments yes, trailing commas no. */
const DIALECT: JsoncDialect = { trailingCommas: false };

interface HookHandler {
  name?: string;
  type?: string;
  command?: string;
  timeout?: number;
  description?: string;
}

interface HookGroup {
  matcher?: string;
  sequential?: boolean;
  hooks?: HookHandler[];
}

/** Ours, whatever path it was installed at — the same marker every host uses,
 * so a hand-moved guard bundle is still recognised as our entry. */
function isOurCommand(handler: HookHandler | null | undefined): boolean {
  return (
    !!handler &&
    isGuardCommand(handler.command)
  );
}

function parseSettings(docText: string | undefined, invalidDocument: string): Record<string, unknown> {
  if (!docText || docText.trim() === "") return {};
  // Never destroy a settings.json we cannot read: refuse loudly instead.
  const parsed = readHostJson(docText, DIALECT, invalidDocument);
  if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) return {};
  return parsed as Record<string, unknown>;
}

/** The document, or undefined when it is blank, unreadable or not an object —
 * for uninstall and the installed check, which never refuse. */
function tryParseSettings(docText: string | undefined): Record<string, unknown> | undefined {
  if (!docText || docText.trim() === "") return undefined;
  try {
    const parsed = readHostJson(docText, DIALECT, INVALID_DOCUMENT);
    return parsed && typeof parsed === "object" && !Array.isArray(parsed) ? (parsed as Record<string, unknown>) : undefined;
  } catch {
    return undefined;
  }
}

/** The per-hook timeout, in the milliseconds Gemini wants, with the same slack
 * over the hold window that policy.ts's hookTimeoutSeconds applies: the host
 * kills a hook that overruns, and a killed hook is a fail-open — which would
 * quietly turn "deny when nobody answers" into "allow when nobody answers". */
function timeoutMs(holdSeconds: number): number {
  const seconds = Math.max(1, Math.round(holdSeconds + HOOK_TIMEOUT_SLACK_SECONDS));
  return seconds * 1000;
}

function mergeGemini(docText: string | undefined, command: string, holdSeconds: number): string {
  const settings = parseSettings(docText, INVALID_DOCUMENT);
  // Canonical form BEFORE any mutation, so an unchanged document is returned
  // byte-identical and the caller can skip the write.
  const before = JSON.stringify(settings);
  // `hooks: []` is valid JSON that Gemini ignores, and a named event set on an
  // array vanishes at stringify time — replace an inert shape rather than
  // reporting success while wiring nothing.
  const hooks =
    settings.hooks && typeof settings.hooks === "object" && !Array.isArray(settings.hooks)
      ? (settings.hooks as Record<string, unknown>)
      : {};
  const groups: HookGroup[] = Array.isArray(hooks[EVENT]) ? (hooks[EVENT] as HookGroup[]) : [];
  const desired: HookHandler = {
    name: "Doorman",
    type: "command",
    command,
    timeout: timeoutMs(holdSeconds),
  };
  const matchesDesired = (h: HookHandler): boolean =>
    h.name === desired.name &&
    h.type === desired.type &&
    h.command === desired.command &&
    h.timeout === desired.timeout &&
    Object.keys(h).length === Object.keys(desired).length;

  let placed = false;
  const next: HookGroup[] = [];
  for (const group of groups) {
    if (!group || typeof group !== "object" || !Array.isArray(group.hooks)) {
      next.push(group);
      continue;
    }
    const kept: HookHandler[] = [];
    let touched = false;
    for (const handler of group.hooks) {
      if (!isOurCommand(handler)) {
        // Somebody else's handler in a group of ours or theirs — not ours to
        // touch, ever.
        kept.push(handler);
        continue;
      }
      if (placed) {
        // A stray second copy of ours, handler by handler.
        touched = true;
        continue;
      }
      placed = true;
      if (matchesDesired(handler)) kept.push(handler);
      else {
        // Update IN PLACE — never remove-and-append. Group order is part of
        // the document other tools wrote; reordering it is not our business.
        kept.push(desired);
        touched = true;
      }
    }
    if (kept.length === 0) continue; // the group held only stray copies of ours
    if (kept.length === 1 && isOurCommand(kept[0])) {
      // Our own group: hold the canonical match-all matcher. A narrowed
      // matcher on a security hook is a partial bypass, not a preference.
      const ours: HookGroup = { ...group, matcher: MATCH_ALL, hooks: kept };
      if (JSON.stringify(ours) !== JSON.stringify(group)) touched = true;
      next.push(touched ? ours : group);
    } else {
      // A shared group is somebody else's structure — leave its shape alone.
      next.push(touched ? { ...group, hooks: kept } : group);
    }
  }
  if (!placed) next.push({ matcher: MATCH_ALL, hooks: [desired] });

  hooks[EVENT] = next;
  settings.hooks = hooks;
  if (docText !== undefined && JSON.stringify(settings) === before) return docText;
  return writeHostJson(docText, settings, DIALECT, INVALID_DOCUMENT);
}

function removeGemini(docText: string | undefined): string | undefined {
  // Uninstall is best-effort: a document we cannot parse has nothing of ours
  // we can safely take out of it.
  const settings = tryParseSettings(docText);
  if (!settings) return undefined;
  const hooks = settings.hooks as Record<string, unknown> | undefined;
  if (!hooks || typeof hooks !== "object" || Array.isArray(hooks) || !Array.isArray(hooks[EVENT])) {
    return undefined;
  }
  const groups = hooks[EVENT] as HookGroup[];
  let removed = false;
  const next: HookGroup[] = [];
  for (const group of groups) {
    if (!group || typeof group !== "object" || !Array.isArray(group.hooks)) {
      next.push(group);
      continue;
    }
    const kept = group.hooks.filter((h) => !isOurCommand(h));
    if (kept.length !== group.hooks.length) removed = true;
    if (kept.length > 0) next.push(kept.length === group.hooks.length ? group : { ...group, hooks: kept });
  }
  if (!removed) return undefined;
  if (next.length > 0) hooks[EVENT] = next;
  else delete hooks[EVENT];
  if (Object.keys(hooks).length === 0) delete settings.hooks;
  return writeHostJson(docText, settings, DIALECT, INVALID_DOCUMENT);
}

function installedGemini(docText: string | undefined, command: string): boolean {
  const settings = tryParseSettings(docText);
  if (!settings) return false;
  const hooks = settings.hooks as Record<string, unknown> | undefined;
  if (!hooks || typeof hooks !== "object" || Array.isArray(hooks) || !Array.isArray(hooks[EVENT])) {
    return false;
  }
  for (const group of hooks[EVENT] as HookGroup[]) {
    if (!group || typeof group !== "object" || !Array.isArray(group.hooks)) continue;
    for (const handler of group.hooks) {
      if (handler && handler.type === "command" && handler.command === command) return true;
    }
  }
  return false;
}

// --- input normalization ---------------------------------------------------

const str = (value: unknown): string | undefined =>
  typeof value === "string" && value !== "" ? value : undefined;

/** The first http(s) URL in a string. `web_fetch` takes a `prompt` that
 * "contains up to 20 valid URLs (starting with `http://` or `https://`) and
 * instructions on how to process them" [5] — there is no `url` field to read,
 * so the URL has to be lifted out of the prose. */
function firstUrl(text: string | undefined): string | undefined {
  if (!text) return undefined;
  const match = /https?:\/\/[^\s<>"'`)\]}]+/i.exec(text);
  return match ? match[0] : undefined;
}

/**
 * `mcp_<server>_<tool>` [2] → `mcp__<server>__<tool>`, the vocabulary every
 * detector and custom rule keys on.
 *
 * THE AMBIGUITY, stated plainly: Gemini joins server and tool with a single
 * `_`, and both halves may themselves contain `_`, so the wire name cannot be
 * split unambiguously. Two rules, in order:
 *
 *  1. If the payload's `mcp_context` names the server and the tool name really
 *     does start with `mcp_<that server>_`, split exactly there. This is the
 *     only correct answer, and it is available whenever Gemini populates the
 *     optional field.
 *  2. Otherwise split on the FIRST underscore after the `mcp_` prefix:
 *     `mcp_github_create_issue` → server `github`, tool `create_issue`. Server
 *     names are usually one token and tool names usually are not, so this is
 *     right far more often than a last-underscore split would be, and it
 *     agrees with custom-rules.ts's MCP_SERVER_RE (which reads the server as
 *     everything before the first `__`). A server literally named `my_server`
 *     is parsed as server `my`, tool `server_…` — wrong, and unfixable from
 *     the name alone; rule 1 is the escape hatch.
 */
function mcpName(toolName: string, mcpContext: unknown): string | undefined {
  if (!toolName.startsWith("mcp_") || toolName.startsWith("mcp__")) return undefined;
  const rest = toolName.slice("mcp_".length);
  if (rest === "") return undefined;
  const server = mcpServerFromContext(mcpContext);
  if (server && rest.startsWith(`${server}_`) && rest.length > server.length + 1) {
    return `mcp__${server}__${rest.slice(server.length + 1)}`;
  }
  const cut = rest.indexOf("_");
  if (cut <= 0 || cut === rest.length - 1) return undefined;
  return `mcp__${rest.slice(0, cut)}__${rest.slice(cut + 1)}`;
}

function mcpServerFromContext(mcpContext: unknown): string | undefined {
  if (!mcpContext || typeof mcpContext !== "object" || Array.isArray(mcpContext)) return undefined;
  const record = mcpContext as Record<string, unknown>;
  for (const key of ["server_name", "serverName", "server"]) {
    const value = str(record[key]);
    if (value) return value;
  }
  return undefined;
}

function normalizeGeminiInput(raw: unknown): GuardHookInput | undefined {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return undefined;
  const payload = raw as Record<string, unknown>;
  const event = str(payload.hook_event_name);
  // Only BeforeTool. A payload with no event name at all but a tool name is
  // still evaluated — the guard would rather look at one extra call than skip
  // a real one over a missing field.
  if (event !== undefined && event !== EVENT) return undefined;
  const toolName = str(payload.tool_name);
  if (!toolName) return undefined;
  const input =
    payload.tool_input && typeof payload.tool_input === "object" && !Array.isArray(payload.tool_input)
      ? (payload.tool_input as Record<string, unknown>)
      : {};
  const base = {
    session_id: str(payload.session_id),
    cwd: str(payload.cwd),
  };

  switch (toolName) {
    case "run_shell_command":
      // `command` is "the exact shell command to execute" [5]. `description`,
      // `dir_path` and `is_background` ride along (P2, 2026-09-10): `dir_path`
      // is where a relative command lands, and every key is text the
      // detectors scan — dropping fields made the card smaller, not safer.
      return { ...base, tool_name: "Bash", tool_input: { ...input, command: input.command } };
    case "write_file":
      return {
        ...base,
        tool_name: "Write",
        tool_input: { ...input, file_path: input.file_path, content: input.content },
      };
    case "replace":
      return {
        ...base,
        tool_name: "Edit",
        tool_input: {
          ...input,
          file_path: input.file_path,
          old_string: input.old_string,
          new_string: input.new_string,
        },
      };
    case "read_file":
      return { ...base, tool_name: "Read", tool_input: { ...input, file_path: input.file_path } };
    case "web_fetch": {
      const url = str(input.url) ?? firstUrl(str(input.prompt));
      // No URL in the prompt at all: pass the call through as itself rather
      // than inventing a WebFetch with nothing to fetch.
      if (!url) return { ...base, tool_name: toolName, tool_input: input };
      return { ...base, tool_name: "WebFetch", tool_input: { ...input, url } };
    }
    default: {
      const mcp = mcpName(toolName, payload.mcp_context);
      // Everything else (glob, grep_search, list_directory, google_web_search,
      // save_memory, …) passes through with its own name and arguments: the
      // custom rules can still match it, and no detector is fooled by a name
      // we did not translate.
      return { ...base, tool_name: mcp ?? toolName, tool_input: input };
    }
  }
}

// --- output ----------------------------------------------------------------

const NO_ASK_SUFFIX =
  "Doorman could not ask in the app; Gemini CLI does not support a native ask, " +
  "so this call is continuing.";

function warnGemini(reason: string): HostEmit {
  const message = reason && reason.trim() !== "" ? reason : "Doorman security policy";
  // `systemMessage` alone: `decision` is not required, and `{}` is documented
  // as "do nothing" [3], so this shows the person why without deciding for
  // them. Pure JSON, nothing else — any stray text on stdout is parsed as an
  // allow with a message, which would make a warning look like a verdict.
  return { stdout: JSON.stringify({ systemMessage: `${message} ${NO_ASK_SUFFIX}` }), exitCode: 0 };
}

function emitGemini(decision: "allow" | "ask" | "deny", reason?: string): HostEmit {
  // Allow prints NOTHING (guard.ts rule 2): our check passed, so Gemini's own
  // confirmation machinery must remain exactly as it was.
  if (decision === "allow") return { exitCode: 0 };
  const message = reason ?? "Doorman security policy";
  // Gemini cannot ask, so an ask that reaches the wire is a warning.
  if (decision === "ask") return warnGemini(message);
  // Exit 0 with `{"decision":"deny"}` — the documented, "preferred for all
  // logic" path [2]. Exit 2 also blocks, but takes its rejection reason from
  // stderr instead of the `reason` field, which loses the structure.
  return { stdout: JSON.stringify({ decision: "deny", reason: message }), exitCode: 0 };
}

export const geminiHost: GuardHostDescriptor = {
  id: "gemini",
  label: "Gemini CLI",
  source: "gemini-cli",

  documents(home: string, env: NodeJS.ProcessEnv): HostDocument[] {
    const system = str(env.GEMINI_CLI_SYSTEM_SETTINGS_PATH) ?? MAC_SYSTEM_SETTINGS;
    return [
      // The one we install into. No documented env var moves it [4].
      { path: `${home}/.gemini/settings.json`, level: "user" },
      // Higher precedence than ours — doctor territory, not install territory.
      { path: ".gemini/settings.json", level: "project" },
      // Higher still in the general settings precedence [4]; read only.
      { path: system, level: "system" },
    ];
  },

  merge: mergeGemini,
  remove: removeGemini,
  installed: installedGemini,
  normalizeInput: normalizeGeminiInput,
  emit: emitGemini,
  warn: warnGemini,

  supportsNativeAsk: false,
  // "Other: Warning. A non-fatal failure occurred; the CLI continues with a
  // warning." [2] — a crashed guard never blocks a call.
  exitSemantics: "fail-open",
  // No fixedTimeoutSeconds: merge() writes `timeout` itself (in ms).

  presencePaths: [".gemini"],
  // Comments are legal in settings.json — see COMMENTS in the header.
  documentFormat: "jsonc",
};
